#!/usr/bin/env python3
"""Generates src/enc/encode_tests.silk: fixed vectors of the encoder at qualities 2 to 9, with the
expected output of the C library, and the check of the dictionary hash tables.

  tools/gen_encode_tests.py REF > src/enc/encode_tests.silk

REF is the C reference driver (tests/reference/build.sh's output). Each vector is a parameter list
and a way of feeding the input (one call, or chunks with flushes) as in tests/reference/ref_tool.c.
The first vector of each quality is checked byte for byte, the others by length and SHA-256.
The digests of the dictionary hash tables come from tools/gen_dictionary_hash.py --digests.
"""
import hashlib, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))


def text_input():
    # Deterministic text with dictionary words, repeats, numbers and some multi-byte UTF-8.
    words = ['the', 'of', 'and', 'compression', 'window', 'brotli', 'dictionary', 'stream', 'über',
             'naïve', 'résumé', 'данные', 'поток', '数据', 'with', 'from', 'that', 'this', 'which',
             '{"name":', '"value"', '</div>', '<p class="x">', '\n', ', ', '. ']
    state = 12345
    out = []
    size = 0
    while size < 2600:
        state = (state * 1103515245 + 12345) & 0x7fffffff
        word = words[(state >> 8) % len(words)]
        if (state >> 4) % 13 == 0:
            word = str((state >> 3) % 1000)
        piece = (word + ' ').encode('utf-8')
        out.append(piece)
        size += len(piece)
    return b''.join(out)[:2600]


def run(ref, data, params, chunk=None, flush=None):
    env = {'BR_MODE': '0', 'BR_PARAMS': params, 'BR_TRACE': '0'}
    if chunk: env['BR_IN'] = str(chunk)
    if flush: env['BR_FLUSH'] = str(flush)
    p = subprocess.run([ref], input=data, capture_output=True, env=env)
    assert p.returncode == 0, (params, p.returncode)
    return p.stdout


def literal(data):
    out = []
    for b in data:
        c = chr(b)
        out.append(c if (b < 128 and c.isalnum()) or c in ' !#$%&()*+,-./:;<=>?@[]^_`|~' else '\\x%02x' % b)
    return 'b"' + ''.join(out) + '"'


def array(digest):
    return '[' + ', '.join('0x%02x' % b for b in digest) + ']'


def digests():
    p = subprocess.run([sys.executable, os.path.join(HERE, 'gen_dictionary_hash.py'), '--digests'], capture_output=True, text=True, check=True)
    values = dict(line.split() for line in p.stdout.splitlines())
    return bytes.fromhex(values['words']), bytes.fromhex(values['lengths'])


def main():
    ref = sys.argv[1]
    data = text_input()
    exact = []
    hashed = []
    for q in range(2, 10):
        exact.append((f'1={q}', 0, 0, run(ref, data, f'1={q}')))
        for params, chunk, flush in [
            (f'1={q},2=16', 0, 0),             # small window: H40, H41, H42 from quality 5
            (f'1={q},5=2000000', 0, 0),        # large input hint: H54, H68, H6
            (f'1={q},2=26,6=1', 0, 0),         # large window: H35, H55, H65
            (f'1={q},0=1,4=1', 0, 0),          # text mode without literal context modeling
            (f'1={q},7=1,8=4,3=16', 0, 0),     # distance parameters and block size
            (f'1={q},2=18', 700, 2),           # streamed, with flushes
        ]:
            out = run(ref, data, params, chunk, flush)
            hashed.append((params, chunk, flush, out))
    words_digest, lengths_digest = digests()

    def params_array(params):
        pairs = [tuple(int(x) for x in p.split('=')) for p in params.split(',')]
        return '[' + ', '.join(f'[{k}, {v}]' for k, v in pairs) + ']', len(pairs)

    lines = []
    for index, (params, chunk, flush, out) in enumerate(exact):
        arr, n = params_array(params)
        lines.append(f'  let e{index}: [[u32; 2]; {n}] = {arr}')
        lines.append(f'  run expectExact(input, &e{index}, {chunk}, {flush}, {literal(out)}, "{params}")')
    for index, (params, chunk, flush, out) in enumerate(hashed):
        arr, n = params_array(params)
        lines.append(f'  let h{index}: [[u32; 2]; {n}] = {arr}')
        lines.append(f'  run expectDigest(input, &h{index}, {chunk}, {flush}, {len(out)}, &{array(hashlib.sha256(out).digest())}, "{params} in {chunk or "one"} {flush or "no"}")')
    body = '\n'.join(lines)

    print(f'''//! Tests of the encoder at qualities 2 to 9 against fixed vectors of google/brotli v1.2.0 (the
//! output of the C library for the same parameters and calls), and of the static dictionary hash
//! tables of `enc.dictionary_hash` against the C tables.

// THIS FILE IS GENERATED by tools/gen_encode_tests.py from the C reference driver. Do not edit it.
import silk.collections.list {{ List }}
import silk.collections.slice {{ Slice }}
import silk.core.effect {{ Effect }}
import silk.crypto.sha2 {{ Sha256 }}
import silk.mem.allocator {{ Allocator, OutOfMemoryError }}
import silk.num.usize
import silk.testing.testing {{ AssertionError, Testing }}
import encode {{ BrotliEncoder, OPERATION_FINISH, OPERATION_FLUSH, OPERATION_PROCESS }}
import enc.dictionary_hash {{ NUM_HASH_BUCKETS, hashLengths, hashWord, hashWordsBytes }}

// The input of all vectors.
const INPUT: &'static [u8] = {literal(data)}

// The SHA-256 of the C tables, the words as 16-bit little-endian values.
const WORDS_SHA256: [u8; 32] = {array(words_digest)}
const LENGTHS_SHA256: [u8; 32] = {array(lengths_digest)}

// Compresses `input` as tests/reference/ref_tool.c does: `params` (id, value) in order, then the
// input in chunks of `chunk` bytes (0: one call) with a flush after every `flush`-th chunk (0:
// never).
effect fn compress(input: &[u8], params: &[[u32; 2]], chunk: usize, flush: usize) -> List<u8> ! AssertionError<'static> | OutOfMemoryError ? &mut Allocator {{
  let mut encoder = run BrotliEncoder.make()
  let mut i: usize = 0
  while i < params.length {{
    run Testing.expect(BrotliEncoder.setParameter(&mut encoder, params[i][0], params[i][1]), "the parameter is accepted")
    i = i + 1
  }}
  let mut out = List<u8>.make()
  let mut buffer = List<u8>.make()
  run List<u8>.appendRepeated(&mut buffer, 0, 65536)
  let step = if chunk == 0 {{ input.length + 1 }} else {{ chunk }}
  let mut pos: usize = 0
  let mut index: usize = 0
  while true {{
    let mut take = input.length - pos
    let mut op = OPERATION_FINISH
    if take > step {{
      take = step
      op = OPERATION_PROCESS
      if flush != 0 && index % flush == flush - 1 {{ op = OPERATION_FLUSH }}
    }}
    let piece = Slice.view<u8>(input, pos, take)
    let mut consumed: usize = 0
    while true {{
      let result = run BrotliEncoder.compressStream(&mut encoder, op, Slice.view<u8>(piece, consumed, take - consumed), List<u8>.asMutSlice(&mut buffer))
      run Testing.expect(result.ok, "the call succeeds")
      consumed = consumed + result.consumed
      run List<u8>.appendSlice(&mut out, Slice.view<u8>(List<u8>.asSlice(&buffer), 0, result.written))
      let more = BrotliEncoder.hasMoreOutput(&encoder)
      if consumed == take && !more && (op != OPERATION_FINISH || BrotliEncoder.isFinished(&encoder)) {{ break }}
    }}
    pos = pos + take
    index = index + 1
    if op == OPERATION_FINISH {{ break }}
  }}
  return move out
}}

effect fn expectExact(input: &[u8], params: &[[u32; 2]], chunk: usize, flush: usize, expected: &[u8], label: string<'static>) -> () ! AssertionError<'static> | OutOfMemoryError ? &mut Allocator {{
  let out = run compress(input, params, chunk, flush)
  let actual = List<u8>.asSlice(&out)
  let mut same = actual.length == expected.length
  let mut i: usize = 0
  while same && i < actual.length {{
    same = actual[i] == expected[i]
    i = i + 1
  }}
  run Testing.expect(same, label)
}}

effect fn expectDigest(input: &[u8], params: &[[u32; 2]], chunk: usize, flush: usize, length: usize, digest: &[u8; 32], label: string<'static>) -> () ! AssertionError<'static> | OutOfMemoryError ? &mut Allocator {{
  let out = run compress(input, params, chunk, flush)
  let actual = List<u8>.asSlice(&out)
  run Testing.expect(actual.length == length && sameDigest(&Sha256.hash(actual), digest), label)
}}

fn sameDigest(a: &[u8; 32], b: &[u8; 32]) -> bool {{
  let mut i: usize = 0
  while i < 32 {{
    if a[i] != b[i] {{ return false }}
    i = i + 1
  }}
  return true
}}

effect fn vectors() -> () ! AssertionError<'static> | OutOfMemoryError ? &mut Allocator {{
  let input = INPUT
{body}
}}

test effect fn encodesLikeTheCLibraryAtQualities2To9() -> () ! AssertionError<'static> | OutOfMemoryError {{
  let mut allocator = Allocator.systemAllocatorProvider()
  run vectors() |> Effect.provideMut<Allocator>(&mut allocator)
}}

effect fn dictionaryHash() -> () ! AssertionError<'static> | OutOfMemoryError ? &mut Allocator {{
  let words = hashWordsBytes()
  let lengths = hashLengths()
  run Testing.expect(words.length == 2 * NUM_HASH_BUCKETS && lengths.length == NUM_HASH_BUCKETS, "the tables have 32768 entries")
  // Hash the decoded words, so that `hashWord` is checked too.
  let mut state = Sha256.make()
  let mut i: usize = 0
  while i < NUM_HASH_BUCKETS {{
    let word = hashWord(words, i)
    let pair: [u8; 2] = [usize.wrappingToU8(word & 0xff), usize.wrappingToU8(usize.shiftRight(word, 8))]
    state.update(&pair)
    i = i + 1
  }}
  run Testing.expect(sameDigest(&state.finish(), &WORDS_SHA256), "kStaticDictionaryHashWords")
  run Testing.expect(sameDigest(&Sha256.hash(lengths), &LENGTHS_SHA256), "kStaticDictionaryHashLengths")
}}

test effect fn hasTheDictionaryHashTablesOfTheCLibrary() -> () ! AssertionError<'static> | OutOfMemoryError {{
  let mut allocator = Allocator.systemAllocatorProvider()
  run dictionaryHash() |> Effect.provideMut<Allocator>(&mut allocator)
}}''')


main()
