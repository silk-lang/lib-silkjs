#!/usr/bin/env python3
"""Writes src/dec/decode_tests.silk: fixed decoder vectors taken from the C reference driver.

  tools/gen_decode_tests.py <reference driver built by tests/reference/build.sh>

Each vector is a stream, the result of decoding it whole (the BROTLI_DECODER_RESULT_* of the last
call, the error code, the SHA-256 of the output and the bytes left after the stream), as the C
library reports them. The corrupt streams are found by mutating reference streams until each error
code the decoder can report on its own input has an example.
"""
import hashlib, random, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ref = sys.argv[1]


def run(data, **env):
    p = subprocess.run([ref], input=data, capture_output=True, env={k: str(v) for k, v in env.items()})
    return p.returncode, p.stdout, p.stderr.decode().strip().split('\n')


def outcome(stream, params=''):
    status, out, trace = run(stream, BR_MODE=1, BR_PARAMS=params)
    calls = [line.split() for line in trace if line.startswith('X ')]
    last = calls[-1]
    rest = int(trace[-1].split()[1]) if trace[-1].startswith('T ') else 0
    return int(last[1]), int(last[5]), hashlib.sha256(out).digest(), rest


def compress(data, params):
    status, out, _ = run(data, BR_MODE=0, BR_PARAMS=params, BR_TRACE=0)
    assert status == 0
    return out


text = (ROOT / 'README.md').read_bytes()[:3000]
vectors = []
vectors.append(('an empty stream', compress(b'', '1=11'), ''))
vectors.append(('one uncompressed meta-block', bytes.fromhex('8b008068690003'), ''))
vectors.append(('a stream of static dictionary words', compress(b'the world of time and life ' * 3, '1=11'), ''))
vectors.append(('text at quality 5, window 10', compress(text, '1=5,2=10'), ''))
vectors.append(('text at quality 11', compress(text, '1=11'), ''))
vectors.append(('a large window stream', compress(text, '1=9,2=28,6=1'), '1=1'))
vectors.append(('a large window stream without the parameter', compress(text, '1=9,2=28,6=1'), ''))
vectors.append(('bytes after the stream', compress(text[:200], '1=4') + b'after', ''))
vectors.append(('a truncated stream', compress(text, '1=6')[:-7], ''))
# BROTLI_DECODER_ERROR_FORMAT_BLOCK_SWITCH, which upstream 0ed4268 added: a command inserts 2^24 + 1
# literals of a one-symbol code (zero bits each) into a meta-block with one literal block type, so
# the literal block length (2^24 with one type) runs out and a block switch is asked for. It needs
# a ring buffer longer than 2^24 (a large window, and no reallocation to the meta-block's size),
# or the ring buffer wraps first.
vectors.append(('a block switch with one block type', bytes.fromhex('115a00000080080bfc02e0f7f41f'), '0=1,1=1'))
rng = random.Random(5)
sources = [compress(text, f'1={q}') for q in range(12)] + [compress(bytes(rng.randrange(256) for _ in range(3000)), '1=5')]
found = {}
for _ in range(60000):
    bad = bytearray(rng.choice(sources))
    kind = rng.randrange(3)
    if kind == 0: bad[rng.randrange(len(bad))] ^= 1 << rng.randrange(8)
    elif kind == 1: bad[min(len(bad) - 1, rng.randrange(40))] = rng.randrange(256)
    else: bad = bytearray(rng.randbytes(rng.randrange(1, 24)))
    result, code, _, _ = outcome(bytes(bad))
    if result == 0 and code not in found:
        found[code] = bytes(bad)
for code in sorted(found, reverse=True):
    vectors.append((f'error {code}', found[code], ''))


def literal(data):
    return 'b"' + ''.join(chr(c) if 32 <= c < 127 and c not in (34, 92) else f'\\x{c:02x}' for c in data) + '"'


lines = ['//! Fixed decoder vectors from google/brotli v1.2.0 with upstream 0ed4268 (the C library\'s',
         '//! result for each stream), decoded whole and one byte at a time into a one-byte output.', '',
         '// THIS FILE IS GENERATED by tools/gen_decode_tests.py from the C reference driver. Do not edit it.',
         'import silk.collections.list { List }', 'import silk.collections.slice { Slice }', 'import silk.crypto.sha2 { Sha256 }',
         'import silk.core.effect { Effect }', 'import silk.mem.allocator { Allocator, OutOfMemoryError }', 'import silk.testing.testing { AssertionError, Testing }',
         'import silk.compress.brotli_tables', 'import decode { BrotliDecoder, PARAM_DISABLE_RING_BUFFER_REALLOCATION, PARAM_LARGE_WINDOW }', '',
         'struct Vector { name: &\'static [u8], stream: &\'static [u8], largeWindow: bool, fixedRing: bool, result: u32, error: i32, digest: [u8; 32], rest: usize }', '',
         'const VECTORS: [Vector; %d] = [' % len(vectors)]
for name, stream, params in vectors:
    result, code, digest, rest = outcome(stream, params)
    lines.append(f'  Vector {{ name: {literal(name.encode())}, stream: {literal(stream)}, largeWindow: {"true" if "1=1" in params else "false"}, fixedRing: {"true" if "0=1" in params else "false"}, result: {result}, error: {code}, digest: [{", ".join(str(b) for b in digest)}], rest: {rest} }},')
lines.append(']')
dictionary = hashlib.sha256(subprocess.run([ref], input=b'', capture_output=True).stdout).digest()
lines += ['', '// The SHA-256 of the C library\'s static dictionary (c/common/dictionary.c, 122,784 bytes).',
          'const DICTIONARY_SHA256: [u8; 32] = [' + ', '.join(str(b) for b in bytes.fromhex('20e42eb1b511c21806d4d227d07e5dd06877d8ce7b3a817f378f313653f35c70')) + ']', '']
lines.append('''// Decodes `stream` with input chunks of `chunk` bytes and an output of `space` bytes; returns the
// last result, the error code, the SHA-256 of the output and the input left after the stream.
fn same(a: &[u8; 32], b: &[u8; 32]) -> bool {
  let mut i: usize = 0
  while i < 32 {
    if a[i] != b[i] { return false }
    i = i + 1
  }
  return true
}

struct Outcome { result: u32, error: i32, digest: [u8; 32], rest: usize }

effect fn decoded(vector: &Vector, chunk: usize, space: usize) -> Outcome ! OutOfMemoryError ? &mut Allocator {
  let mut decoder = run BrotliDecoder.make()
  if vector.largeWindow { let _accepted = BrotliDecoder.setParameter(&mut decoder, PARAM_LARGE_WINDOW, 1) }
  if vector.fixedRing { let _accepted = BrotliDecoder.setParameter(&mut decoder, PARAM_DISABLE_RING_BUFFER_REALLOCATION, 1) }
  let mut out = List<u8>.make()
  let mut buffer = List<u8>.make()
  run List<u8>.appendRepeated(&mut buffer, 0, space)
  let stream = vector.stream
  let mut position: usize = 0
  let mut result: u32 = 0
  while true {
    let mut take = stream.length - position
    if take > chunk { take = chunk }
    let step = run BrotliDecoder.decompressStream(&mut decoder, Slice.view<u8>(stream, position, take), List<u8>.asMutSlice(&mut buffer))
    run List<u8>.appendSlice(&mut out, Slice.view<u8>(List<u8>.asSlice(&buffer), 0, step.written))
    position = position + step.consumed
    result = step.result
    if result == 0 || result == 1 { break }
    if result == 2 && position == stream.length { break }
  }
  return Outcome { result: result, error: BrotliDecoder.errorCode(&decoder), digest: Sha256.hash(List<u8>.asSlice(&out)), rest: stream.length - position }
}

// Decoding in pieces, a corrupt stream writes as much as the pieces allowed before its error (the C
// library does the same; tests/differential.py compares that call for call), so `whole` false
// checks only the streams that decode.
effect fn check(chunk: usize, space: usize, whole: bool) -> () ! AssertionError<'static> | OutOfMemoryError ? &mut Allocator {
  let mut index: usize = 0
  while index < VECTORS.length {
    let vector = &VECTORS[index]
    index = index + 1
    if !whole && vector.result != 1 { continue }
    let got = run decoded(vector, chunk, space)
    run Testing.expect(got.result == vector.result, "the result of the last call is the C library's")
    if got.result == 0 { run Testing.expect(got.error == vector.error, "the error code is the C library's") }
    run Testing.expect(same(&got.digest, &vector.digest), "the output is the C library's")
    if got.result == 1 { run Testing.expect(got.rest == vector.rest, "the bytes after the stream are left") }
  }
}

test effect fn decodesWhole() -> () ! AssertionError<'static> | OutOfMemoryError {
  let mut allocator = Allocator.systemAllocatorProvider()
  run check(1048576, 1048576, true) |> Effect.provideMut<Allocator>(&mut allocator)
}

test effect fn decodesOneByteAtATime() -> () ! AssertionError<'static> | OutOfMemoryError {
  let mut allocator = Allocator.systemAllocatorProvider()
  run check(1, 1, false) |> Effect.provideMut<Allocator>(&mut allocator)
}

test effect fn decodesInSmallPieces() -> () ! AssertionError<'static> | OutOfMemoryError {
  let mut allocator = Allocator.systemAllocatorProvider()
  run check(3, 4096, false) |> Effect.provideMut<Allocator>(&mut allocator)
}

test effect fn usesTheStaticDictionaryOfTheCLibrary() -> () ! AssertionError<'static> {
  run Testing.expect(same(&Sha256.hash(brotli_tables.words()), &DICTIONARY_SHA256), "the dictionary is the C library's")
}

test effect fn reportsVersion120() -> () ! AssertionError<'static> {
  run Testing.expect(BrotliDecoder.version() == 16785408, "1.2.0")
}
''')
(ROOT / 'src/dec/decode_tests.silk').write_text('\n'.join(lines))
print(len(vectors), 'vectors; error codes', sorted(found))
