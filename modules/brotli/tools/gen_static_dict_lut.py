#!/usr/bin/env python3
"""Generates src/enc/static_dict_lut.silk from google/brotli v1.2.0 c/enc/static_dict_lut_inc.h.

    python3 tools/gen_static_dict_lut.py <brotli checkout>/c/enc/static_dict_lut_inc.h > src/enc/static_dict_lut.silk

The tables become two byte strings: the buckets as little-endian 16-bit values, and the words as
4 bytes each (len, transform, idx low byte, idx high byte), the layout of C's `DictWord`. The
script prints the FNV-1a 64 hashes of both byte strings on stderr; `enc.encode_hq_tests` checks
the tables against them.
"""
import hashlib
import re
import sys


def fnv1a64(data):
    h = 0xcbf29ce484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001b3) & 0xffffffffffffffff
    return h

def silk_bytes(data, width=96):
    out = []
    line = []
    length = 0
    for b in data:
        if 0x20 <= b < 0x7f and b not in (0x22, 0x5c, 0x7b, 0x7d):
            piece = chr(b)
        else:
            piece = '\\x%02x' % b
        line.append(piece)
        length += len(piece)
        if length >= width:
            out.append(''.join(line))
            line = []
            length = 0
    if line:
        out.append(''.join(line))
    return out

def main():
    path = sys.argv[1]
    raw = open(path, 'rb').read()
    sha = hashlib.sha256(raw).hexdigest()
    text = re.sub(r'\s+', '', re.sub(r'/\*.*?\*/', '', raw.decode('ascii'), flags=re.S))
    buckets_src = re.search(r'kStaticDictionaryBuckets\[[^\]]*\]\s*=\s*\{(.*?)\};', text, re.S).group(1)
    words_src = re.search(r'kStaticDictionaryWords\[[^\]]*\]\s*=\s*\{(.*)\};', text, re.S).group(1)
    buckets = [int(x) for x in re.findall(r'\d+', buckets_src)]
    words = [tuple(int(v) for v in m) for m in re.findall(r'\{(\d+),(\d+),(\d+)\}', words_src)]
    assert len(buckets) == 32768, len(buckets)
    assert len(words) == 31705, len(words)
    bucket_bytes = bytearray()
    for v in buckets:
        bucket_bytes += bytes([v & 0xff, v >> 8])
    word_bytes = bytearray()
    for (l, t, i) in words:
        word_bytes += bytes([l, t, i & 0xff, i >> 8])
    w = sys.stdout.write
    w('//! The lookup table of the static dictionary for the encoder: google/brotli v1.2.0\n')
    w('//! `c/enc/static_dict_lut.h` and `static_dict_lut_inc.h` (`kStaticDictionaryBuckets`,\n')
    w('//! `kStaticDictionaryWords`), as byte strings.\n')
    w('//!\n')
    w('//! THIS FILE IS GENERATED by tools/gen_static_dict_lut.py from static_dict_lut_inc.h with\n')
    w('//! SHA-256 %s. Do not edit it.\n' % sha)
    w('import silk.num.u8\n')
    w('import silk.num.u16\n\n')
    w('/// `BROTLI_ENC_STATIC_DICT_LUT_NUM_BUCKETS`.\n')
    w('pub const NUM_BUCKETS: usize = 32768\n')
    w('/// `BROTLI_ENC_STATIC_DICT_LUT_NUM_ITEMS`.\n')
    w('pub const NUM_ITEMS: usize = 31705\n')
    w('\n')
    w('/// `kStaticDictionaryBuckets[key]`: the first word of the bucket of a `Hash15` key, or 0 for an\n')
    w('/// empty bucket.\n')
    w('@inlineAlways\n')
    w('pub fn bucket(key: usize) -> usize {\n')
    w('  let table = bucketBytes()\n')
    w('  return u8.toUsize(table[2 * key]) | u16.toUsize(u16.shiftLeft(u8.toU16(table[2 * key + 1]), 8))\n')
    w('}\n\n')
    w('/// `kStaticDictionaryBuckets` as little-endian 16-bit values.\n')
    w('pub fn bucketBytes() -> &\'static [u8] {\n')
    w('  return b"')
    w(''.join(silk_bytes(bucket_bytes)))
    w('"\n}\n\n')
    w('/// `kStaticDictionaryWords`: 4 bytes for each word, `len` (the highest bit marks the last word\n')
    w('/// of a bucket), `transform` and the 16-bit `idx`, little-endian.\n')
    w('pub fn wordBytes() -> &\'static [u8] {\n')
    w('  return b"')
    w(''.join(silk_bytes(word_bytes)))
    w('"\n}\n')
    sys.stderr.write('sha256 %s buckets %016x words %016x\n' % (sha, fnv1a64(bucket_bytes), fnv1a64(word_bytes)))

main()
