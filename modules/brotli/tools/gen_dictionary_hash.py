#!/usr/bin/env python3
"""Generates src/enc/dictionary_hash.silk from google/brotli v1.2.0 c/enc/dictionary_hash_inc.h.

  tools/gen_dictionary_hash.py [--digests] [PATH/TO/dictionary_hash_inc.h] > src/enc/dictionary_hash.silk

The C file holds the two 32768-entry tables of the encoder's hash of the static dictionary
(`kStaticDictionaryHashWords`, uint16_t, and `kStaticDictionaryHashLengths`, uint8_t). The Silk
module holds them as byte strings (the words little endian), which compile much faster than array
constants of that size. The input is pinned by its SHA-256. With --digests it prints the SHA-256
of both tables (the words as 16-bit little-endian values) instead, which the tests of
src/enc/encode_tests.silk check the decoded tables against.
"""
import hashlib, re, sys

PINNED = '6effa6998dbb024d12766b9240beb549a8ee50fd6fdadf4a61ec8899eb9ac4d4'
DEFAULT = '/root/deps/src/brotli/c/enc/dictionary_hash_inc.h'
COUNT = 32768


def table(source, name):
    match = re.search(r'\b' + name + r'\[BROTLI_ENC_NUM_HASH_BUCKETS\]\s*=\s*\{([^}]*)\}', source)
    values = [int(v) for v in match.group(1).replace('\n', '').split(',') if v.strip()]
    assert len(values) == COUNT, (name, len(values))
    return values


def literal(data):
    out = []
    for b in data:
        c = chr(b)
        out.append(c if (b < 128 and c.isalnum()) or c in ' !#$%&()*+,-./:;<=>?@[]^_`|~' else '\\x%02x' % b)
    return 'b"' + ''.join(out) + '"'


def main():
    paths = [a for a in sys.argv[1:] if not a.startswith('--')]
    path = paths[0] if paths else DEFAULT
    raw = open(path, 'rb').read()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != PINNED:
        sys.exit(f'{path}: SHA-256 {digest} is not the pinned {PINNED}')
    source = raw.decode('ascii')
    words = table(source, 'kStaticDictionaryHashWords')
    lengths = table(source, 'kStaticDictionaryHashLengths')
    assert all(0 <= w < 65536 for w in words) and all(0 <= l < 256 for l in lengths)
    words_bytes = b''.join(w.to_bytes(2, 'little') for w in words)
    lengths_bytes = bytes(lengths)
    if '--digests' in sys.argv:
        print('words', hashlib.sha256(words_bytes).hexdigest())
        print('lengths', hashlib.sha256(lengths_bytes).hexdigest())
        return
    print(f'''//! The hash table of the static dictionary for the encoder's match finders: the data of
//! google/brotli v1.2.0 `c/enc/dictionary_hash_inc.h` (`kStaticDictionaryHashWords` and
//! `kStaticDictionaryHashLengths`, see `c/enc/dictionary_hash.h`).
//!
//! A bucket is `Hash14(word) * 2 + (length < 8)`: two buckets for each hash, one for shorter words
//! and one for longer words. Each holds the length of one dictionary word (0 for none) and its
//! index among the words of that length.

// THIS FILE IS GENERATED by tools/gen_dictionary_hash.py from dictionary_hash_inc.h (SHA-256
// {PINNED}). Do not edit it.
import silk.num.u8
import silk.num.usize

/// The number of buckets, `BROTLI_ENC_NUM_HASH_BUCKETS`.
pub const NUM_HASH_BUCKETS: usize = {COUNT}

/// `kStaticDictionaryHashWords` as 16-bit little-endian values.
pub fn hashWordsBytes() -> &'static [u8] {{
  return {literal(words_bytes)}
}}

/// `kStaticDictionaryHashLengths`.
pub fn hashLengths() -> &'static [u8] {{
  return {literal(lengths_bytes)}
}}

/// `kStaticDictionaryHashWords[bucket]`.
@inlineAlways
pub fn hashWord(words: &[u8], bucket: usize) -> usize {{
  return u8.toUsize(words[2 * bucket]) | usize.shiftLeft(u8.toUsize(words[2 * bucket + 1]), 8)
}}''')


main()
